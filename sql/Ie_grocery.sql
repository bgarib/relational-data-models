CREATE TABLE address_type (
  TYPE_ID CHAR(1) NOT NULL,
  DESCRIPTION VARCHAR(40) NOT NULL,
  PRIMARY KEY (TYPE_ID)
);

CREATE TABLE zipcode (
  ZIPCODE INT NOT NULL,
  COUNTRY VARCHAR(20) NOT NULL,
  CITY VARCHAR(20) NOT NULL,
  STATE VARCHAR(20) NOT NULL,
  PRIMARY KEY (ZIPCODE, COUNTRY)
);

CREATE TABLE address (
  ADDRESS_ID INT NOT NULL,
  TYPE_ID CHAR(1) NOT NULL,
  NAME VARCHAR(40) NOT NULL,
  NUMBER SMALLINT,
  ZIPCODE INT NOT NULL,
  COUNTRY VARCHAR(20) NOT NULL,
  PRIMARY KEY (ADDRESS_ID),
  CONSTRAINT fk_address_type FOREIGN KEY (TYPE_ID) REFERENCES address_type (TYPE_ID),
  CONSTRAINT fk_address_zip FOREIGN KEY (ZIPCODE, COUNTRY) REFERENCES zipcode (ZIPCODE, COUNTRY)
);

CREATE TABLE contact (
  CONTACT_ID INT NOT NULL,
  NAME VARCHAR(40) NOT NULL,
  ADDRESS_ID INT,
  PRIMARY KEY (CONTACT_ID),
  CONSTRAINT fk_contact_address FOREIGN KEY (ADDRESS_ID) REFERENCES address (ADDRESS_ID)
);

CREATE TABLE brand (
  BRAND_ID INT NOT NULL,
  NAME VARCHAR(40) NOT NULL,
  DESCRIPTION VARCHAR(128),
  CONTACT_ID INT,
  PRIMARY KEY (BRAND_ID),
  CONSTRAINT fk_brand_contact FOREIGN KEY (CONTACT_ID) REFERENCES contact (CONTACT_ID)
);

CREATE TABLE ccentry_methd (
  CCMETHD CHAR(1) NOT NULL,
  DESCRIPTION VARCHAR(40) NOT NULL,
  PRIMARY KEY (CCMETHD)
);

CREATE TABLE currency (
  CURRENCY_ID CHAR(3) NOT NULL,
  CURRENCY_CODE SMALLINT NOT NULL,
  DESCRIPTION VARCHAR(40) NOT NULL,
  PRIMARY KEY (CURRENCY_ID)
);

CREATE TABLE ccpayment_state (
  CCSTATE CHAR(1) NOT NULL,
  DESCRIPTION VARCHAR(40) NOT NULL,
  PRIMARY KEY (CCSTATE)
);

CREATE TABLE ccpayment (
  CCPAYMENT_ID BIGINT NOT NULL,
  CCPAYTRAN_ID BIGINT,
  CURRENCY_ID CHAR(3) NOT NULL,
  EXPECTED_AMOUNT DECIMAL(20,5) NOT NULL,
  APPROVING_AMOUNT DECIMAL(20,5),
  APPROVED_AMOUNT DECIMAL(20,5),
  CCPAYMENT_STATE CHAR(1) NOT NULL,
  TIMECREATED TIMESTAMP_F NOT NULL,
  TIMEUPDATED TIMESTAMP_F,
  TIMEEXPIRED TIMESTAMP_F,
  PRIMARY KEY (CCPAYMENT_ID),
  CONSTRAINT fk_ccpayment_currency FOREIGN KEY (CURRENCY_ID) REFERENCES currency (CURRENCY_ID),
  CONSTRAINT fk_ccpayment_state FOREIGN KEY (CCPAYMENT_STATE) REFERENCES ccpayment_state (CCSTATE)
);

CREATE TABLE ccpayment_type (
  CCTYPE CHAR(2) NOT NULL,
  DESCRIPTION VARCHAR(40) NOT NULL,
  PRIMARY KEY (CCTYPE)
);

CREATE TABLE ccpayment_card (
  CCPAYMENT_ID BIGINT NOT NULL,
  PAYMENT_TYPE CHAR(2) NOT NULL,
  IS_ENCRYPT CHAR(1) NOT NULL,
  CARD_NUMBER VARCHAR(64) NOT NULL,
  BANKNAME VARCHAR(64) NOT NULL,
  CCEXPDATE CHAR(6) NOT NULL,
  CCENTRY_METHD CHAR(1) NOT NULL,
  PRIMARY KEY (CCPAYMENT_ID),
  CONSTRAINT fk_card_method FOREIGN KEY (CCENTRY_METHD) REFERENCES ccentry_methd (CCMETHD),
  CONSTRAINT fk_card_payment FOREIGN KEY (CCPAYMENT_ID) REFERENCES ccpayment (CCPAYMENT_ID),
  CONSTRAINT fk_card_type FOREIGN KEY (PAYMENT_TYPE) REFERENCES ccpayment_type (CCTYPE)
);

CREATE TABLE color (
  COLOR_ID BIGINT NOT NULL,
  RGB_RED SMALLINT NOT NULL,
  RGB_GREEN SMALLINT NOT NULL,
  RGB_BLUE SMALLINT NOT NULL,
  HEX_CODE CHAR(6) NOT NULL,
  COLOR_NAME VARCHAR(20) NOT NULL,
  PRIMARY KEY (COLOR_ID)
);

CREATE TABLE location_type (
  TYPE_ID CHAR(1) NOT NULL,
  DESCRIPTION VARCHAR(40) NOT NULL,
  PRIMARY KEY (TYPE_ID)
);

CREATE TABLE location (
  LOCATION_ID BIGINT NOT NULL,
  TYPE_ID CHAR(1) NOT NULL,
  ADDRESS_ID INT NOT NULL,
  PRIMARY KEY (LOCATION_ID),
  CONSTRAINT fk_location_address FOREIGN KEY (ADDRESS_ID) REFERENCES address (ADDRESS_ID),
  CONSTRAINT fk_location_type FOREIGN KEY (TYPE_ID) REFERENCES location_type (TYPE_ID)
);

CREATE TABLE phones (
  LOCATION_ID BIGINT NOT NULL,
  NUMSEQ SMALLINT NOT NULL,
  EXTERNAL VARCHAR(20),
  INTERNAL VARCHAR(20),
  DESCRIPTION VARCHAR(40) NOT NULL,
  PRIMARY KEY (LOCATION_ID, NUMSEQ),
  CONSTRAINT fk_phones_location FOREIGN KEY (LOCATION_ID) REFERENCES location (LOCATION_ID)
);

CREATE TABLE unit_measure (
  METRIC_CODE CHAR(2) NOT NULL,
  NAME VARCHAR(20) NOT NULL,
  DESCRIPTION VARCHAR(128),
  PRIMARY KEY (METRIC_CODE)
);

CREATE TABLE supplier (
  SUPPLIER_ID INT NOT NULL,
  NAME VARCHAR(40) NOT NULL,
  CONTACT_ID INT NOT NULL,
  PAYMENT_TERMS VARCHAR(1024),
  PRIMARY KEY (SUPPLIER_ID),
  CONSTRAINT fk_supplier_contact FOREIGN KEY (CONTACT_ID) REFERENCES contact (CONTACT_ID)
);

CREATE TABLE product (
  PRODUCT_ID BIGINT NOT NULL,
  CATEGORY_ID BIGINT NOT NULL,
  SIZE_CODE CHAR(2),
  SIZE DECIMAL(10,2),
  WEIGHT_CODE CHAR(2),
  WEIGHT DECIMAL(10,2),
  PACK_CODE CHAR(2),
  COLOR_ID BIGINT,
  NAME VARCHAR(40) NOT NULL,
  BRAND_ID INT,
  SUPPLIER_ID INT NOT NULL,
  SHORT_DESCRIPTION VARCHAR(128) NOT NULL,
  LONG_DESCRIPTION VARCHAR(1024) NOT NULL,
  THUMBNAIL VARCHAR(254),
  FULLIMAGE VARCHAR(254),
  PRIMARY KEY (PRODUCT_ID),
  CONSTRAINT fk_product_brand FOREIGN KEY (BRAND_ID) REFERENCES brand (BRAND_ID),
  CONSTRAINT fk_product_color FOREIGN KEY (COLOR_ID) REFERENCES color (COLOR_ID),
  CONSTRAINT fk_product_pack FOREIGN KEY (PACK_CODE) REFERENCES unit_measure (METRIC_CODE),
  CONSTRAINT fk_product_size FOREIGN KEY (SIZE_CODE) REFERENCES unit_measure (METRIC_CODE),
  CONSTRAINT fk_product_supplier FOREIGN KEY (SUPPLIER_ID) REFERENCES supplier (SUPPLIER_ID),
  CONSTRAINT fk_product_weight FOREIGN KEY (WEIGHT_CODE) REFERENCES unit_measure (METRIC_CODE)
);

CREATE TABLE price (
  PRODUCT_ID BIGINT NOT NULL,
  COST_CURRENCY CHAR(3) NOT NULL,
  COST DECIMAL(10,2) NOT NULL,
  PRICE_CURRENCY CHAR(3) NOT NULL,
  PRICE DECIMAL(10,2) NOT NULL,
  PRICE_PROMOTION DECIMAL(10,2),
  TAXES DECIMAL(10,2),
  PRIMARY KEY (PRODUCT_ID),
  CONSTRAINT fk_price_cost_cur FOREIGN KEY (COST_CURRENCY) REFERENCES currency (CURRENCY_ID),
  CONSTRAINT fk_price_price_cur FOREIGN KEY (PRICE_CURRENCY) REFERENCES currency (CURRENCY_ID),
  CONSTRAINT fk_price_product FOREIGN KEY (PRODUCT_ID) REFERENCES product (PRODUCT_ID)
);

CREATE TABLE store (
  STORE_ID SMALLINT NOT NULL,
  LOCATION_ID BIGINT NOT NULL,
  PRIMARY KEY (STORE_ID),
  CONSTRAINT fk_store_location FOREIGN KEY (LOCATION_ID) REFERENCES location (LOCATION_ID)
);

CREATE TABLE ticket (
  TICKET_ID BIGINT NOT NULL,
  TIMEPLACED TIMESTAMP_F NOT NULL,
  STORE_ID SMALLINT NOT NULL,
  CASHIER_ID INT NOT NULL,
  TOTAL_PRODUCT DECIMAL(20,5) NOT NULL,
  TOTAL_TAX DECIMAL(20,5) NOT NULL,
  TOTAL_ORDER DECIMAL(20,5) NOT NULL,
  CURRENCY_ID CHAR(3) NOT NULL,
  PAYMENT_ID BIGINT,
  PRIMARY KEY (TICKET_ID),
  CONSTRAINT fk_ticket_currency FOREIGN KEY (CURRENCY_ID) REFERENCES currency (CURRENCY_ID),
  CONSTRAINT fk_ticket_payment FOREIGN KEY (PAYMENT_ID) REFERENCES ccpayment (CCPAYMENT_ID),
  CONSTRAINT fk_ticket_store FOREIGN KEY (STORE_ID) REFERENCES store (STORE_ID)
);

CREATE TABLE ticket_item (
  TICKET_ID BIGINT NOT NULL,
  NUMSEQ SMALLINT NOT NULL,
  PRODUCT_ID BIGINT NOT NULL,
  DESCRIPTION VARCHAR(80) NOT NULL,
  QUANTITY SMALLINT NOT NULL,
  PRICE DECIMAL(20,5) NOT NULL,
  TAX_AMOUNT DECIMAL(20,5),
  PRODUCT_AMOUNT DECIMAL(20,5) NOT NULL,
  PRIMARY KEY (TICKET_ID, NUMSEQ),
  CONSTRAINT fk_item_product FOREIGN KEY (PRODUCT_ID) REFERENCES product (PRODUCT_ID),
  CONSTRAINT fk_item_ticket FOREIGN KEY (TICKET_ID) REFERENCES ticket (TICKET_ID)
);
