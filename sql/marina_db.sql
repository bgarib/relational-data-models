CREATE TABLE marina (
  MARINA_ID INT NOT NULL,
  NAME VARCHAR(100) NOT NULL,
  CITY VARCHAR(60) NOT NULL,
  COUNTRY VARCHAR(60) NOT NULL,
  TOTAL_BERTHS SMALLINT NOT NULL,
  PHONE VARCHAR(20),
  EMAIL VARCHAR(100),
  PRIMARY KEY (MARINA_ID),
  UNIQUE KEY uq_marina_name (NAME)
);

CREATE TABLE person (
  PERSON_ID INT NOT NULL,
  FIRST_NAME VARCHAR(50) NOT NULL,
  LAST_NAME VARCHAR(50) NOT NULL,
  DOCUMENT_ID VARCHAR(20) NOT NULL,
  EMAIL VARCHAR(100) NOT NULL,
  PHONE VARCHAR(20),
  NATIONALITY VARCHAR(50),
  BIRTH_DATE DATE,
  PRIMARY KEY (PERSON_ID),
  UNIQUE KEY uq_person_document (DOCUMENT_ID),
  UNIQUE KEY uq_person_email (EMAIL)
);

CREATE TABLE berth (
  BERTH_ID INT NOT NULL,
  MARINA_ID INT NOT NULL,
  BERTH_CODE VARCHAR(10) NOT NULL,
  MAX_LENGTH_M DECIMAL(5,2) NOT NULL,
  MAX_BEAM_M DECIMAL(4,2) NOT NULL,
  DEPTH_M DECIMAL(4,2) NOT NULL,
  HAS_ELECTRICITY TINYINT(1) NOT NULL,
  MONTHLY_FEE DECIMAL(8,2) NOT NULL,
  RENTER_PERSON_ID INT,
  RENTAL_START_DATE DATE,
  RENTAL_END_DATE DATE,
  PRIMARY KEY (BERTH_ID),
  UNIQUE KEY uq_berth_code_per_marina (MARINA_ID, BERTH_CODE),
  UNIQUE KEY uq_berth_renter (BERTH_ID, RENTER_PERSON_ID),
  CONSTRAINT fk_berth_marina FOREIGN KEY (MARINA_ID) REFERENCES marina (MARINA_ID),
  CONSTRAINT fk_berth_renter FOREIGN KEY (RENTER_PERSON_ID) REFERENCES person (PERSON_ID)
);

CREATE TABLE vessel (
  VESSEL_ID INT NOT NULL,
  OWNER_PERSON_ID INT NOT NULL,
  BERTH_ID INT,
  NAME VARCHAR(60) NOT NULL,
  REGISTRATION_NUMBER VARCHAR(20) NOT NULL,
  VESSEL_TYPE ENUM('Sailboat', 'Motorboat', 'Catamaran', 'Yacht', 'RIB') NOT NULL,
  LENGTH_M DECIMAL(5,2) NOT NULL,
  BEAM_M DECIMAL(4,2) NOT NULL,
  BUILD_YEAR SMALLINT,
  PRIMARY KEY (VESSEL_ID),
  UNIQUE KEY uq_vessel_registration (REGISTRATION_NUMBER),
  CONSTRAINT fk_vessel_owner FOREIGN KEY (OWNER_PERSON_ID) REFERENCES person (PERSON_ID),
  CONSTRAINT fk_vessel_rented_berth FOREIGN KEY (BERTH_ID, OWNER_PERSON_ID) REFERENCES berth (BERTH_ID, RENTER_PERSON_ID)
);
